# Módulo: Pilha (LIFO - Último a entrar, primeiro a sair)
# Implementação baseada em funções (sem classes).

# Função: criar_pilha()
# - Cria e retorna uma nova pilha vazia (uma lista []).

# Função: empilhar(pilha, item)
# - Adiciona um registro de ação no topo da pilha (pilha.append(item)).

# Função: desempilhar(pilha)
# - Remove e retorna a última ação registrada (pilha.pop()).
# - Tratar caso a pilha esteja vazia (retornar None).

# Função: topo_pilha(pilha)
# - Retorna o elemento do topo sem remover (pilha[-1]).

# Função: pilha_vazia(pilha)
# - Retorna True se a pilha estiver vazia (len(pilha) == 0), senão False.

# Função: tamanho_pilha(pilha)
# - Retorna a quantidade de ações na pilha (len(pilha)).

# Função: listar_pilha(pilha)
# - Retorna ou exibe as ações armazenadas para histórico.
